// File: packages/vue/scripts/generate-index.mjs
// Scans src/components and src/blocks and (re)writes src/index.ts and manifest.json.
// Run: npm run generate -w @birdycom/omniaui-vue

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = path.join(root, 'src')

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

// Sub-parts that render markup of another snippet.
const snippetAlias = {
  'avatar-group': 'avatar',
  'dropdown-item': 'dropdown',
  'dropdown-label': 'dropdown',
  'dropdown-separator': 'dropdown',
  'navmenu-list': 'navmenu',
  'accordion-item': 'accordion',
  'toast-container': 'toast',
  'sidebar-group': 'sidebar',
  'sidebar-menu': 'sidebar',
  'sidebar-menu-button': 'sidebar',
  'sidebar-collapsible': 'sidebar',
  'sidebar-separator': 'sidebar',
  'settings-section': 'settings-page',
  'settings-row': 'settings-page',
  'message-list': 'message',
  'attachment-list': 'attachment',
  'attachment-image': 'attachment',
  'attachment-thumb': 'attachment',
  status: 'status-dot',
  'glass-panel': 'glass',
  'titlebar-window': 'titlebar',
  'titlebar-button': 'titlebar',
  'titlebar-body': 'titlebar',
}

const entries = []
for (const [dir, kind] of [['components', 'component'], ['blocks', 'block']]) {
  for (const file of fs.readdirSync(path.join(src, dir)).filter((f) => f.endsWith('.vue')).sort()) {
    const name = file.replace(/\.vue$/, '')
    const bare = name.replace(/^Oc(Block)?/, '')
    const slug = kebab(bare)
    const snippetSlug = snippetAlias[slug.replace(/^block-/, '')] ?? snippetAlias[slug] ?? slug
    const snippet =
      kind === 'component'
        ? `@birdycom/omniaui/snippets/${snippetSlug}.html`
        : `@birdycom/omniaui-blocks/blocks/${snippetSlug}.html`
    const snippetFile = path.join(
      root,
      '..',
      kind === 'component' ? 'ui/snippets' : 'blocks/blocks',
      `${snippetSlug}.html`,
    )
    const text = fs.readFileSync(path.join(src, dir, file), 'utf8')
    const types = [...text.matchAll(/^export (?:interface|type) (\w+)/gm)].map((m) => m[1])
    entries.push({
      name,
      kind,
      file: `src/${dir}/${file}`,
      snippet: fs.existsSync(snippetFile) ? snippet : null,
      types,
      dir,
    })
  }
}

const lines = [
  '// File: packages/vue/src/index.ts (generated by scripts/generate-index.mjs - do not edit by hand)',
  "import type { App, Component } from 'vue'",
  '',
]
for (const e of entries) lines.push(`import ${e.name} from './${e.dir}/${e.name}.vue'`)
lines.push('')
lines.push('export {')
for (const e of entries) lines.push(`  ${e.name},`)
lines.push('}')
lines.push('')
for (const e of entries) {
  if (e.types.length) lines.push(`export type { ${e.types.join(', ')} } from './${e.dir}/${e.name}.vue'`)
}
lines.push('')
lines.push("export { useToast } from './composables/useToast'")
lines.push("export type { ToastItem, ToastOptions, ToastVariant } from './composables/useToast'")
// Used by the OmniaUI Pro blocks (@birdycom/omniaui-pro-vue) for their id wiring.
lines.push("export { useUid } from './composables/useUid'")
lines.push('')
lines.push('/** Every component and block by name, e.g. { OcButton, OcBlockHero, ... }. */')
lines.push('export const components: Record<string, Component> = {')
for (const e of entries) lines.push(`  ${e.name},`)
lines.push('}')
lines.push('')
lines.push('/** Vue plugin: app.use(OmniaVue) registers every Oc* component globally. */')
lines.push('export const OmniaVue = {')
lines.push('  install(app: App) {')
lines.push('    for (const [name, component] of Object.entries(components)) app.component(name, component)')
lines.push('  },')
lines.push('}')
lines.push('')
lines.push('export default OmniaVue')
lines.push('')
fs.writeFileSync(path.join(src, 'index.ts'), lines.join('\n'))

const manifest = {
  items: entries.map(({ name, kind, file, snippet }) => ({ name, kind, file, snippet })),
}
fs.writeFileSync(path.join(root, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')
console.log(`[vue] ${entries.length} entries (${entries.filter((e) => e.kind === 'component').length} components, ${entries.filter((e) => e.kind === 'block').length} blocks)`)
