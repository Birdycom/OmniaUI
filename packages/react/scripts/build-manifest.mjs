// File: packages/react/scripts/build-manifest.mjs
// Generates src/index.ts and manifest.json from the files in src/components and src/blocks.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const list = (dir) => fs.readdirSync(path.join(root, "src", dir)).filter((f) => f.endsWith(".tsx")).sort();

const items = [];
for (const f of list("components")) {
  const n = f.replace(/\.tsx$/, "");
  const snippet = `snippets/${kebab(n)}.html`;
  const has = fs.existsSync(path.join(root, "..", "ui", snippet));
  items.push({ name: kebab(n), kind: "component", file: `src/components/${f}`, snippet: has ? `@birdycom/omniaui/${snippet}` : null });
}
for (const f of list("blocks")) {
  const n = f.replace(/\.tsx$/, "").replace(/^Block/, "");
  const snippet = `blocks/${kebab(n)}.html`;
  const has = fs.existsSync(path.join(root, "..", "blocks", snippet));
  items.push({ name: kebab(n), kind: "block", file: `src/blocks/${f}`, snippet: has ? `@birdycom/omniaui-blocks/${snippet}` : null });
}

const exportsList = [
  `export * from "./hooks";`,
  // attrs/mod/callAll are also used by the OmniaUI Pro blocks (@birdycom/omniaui-pro-react).
  `export { attrs, callAll, cx, mod } from "./utils";`,
  ...list("components").map((f) => `export * from "./components/${f.replace(/\.tsx$/, "")}";`),
  ...list("blocks").map((f) => `export * from "./blocks/${f.replace(/\.tsx$/, "")}";`),
];
fs.writeFileSync(path.join(root, "src", "index.ts"), `// Generated by scripts/build-manifest.mjs\n${exportsList.join("\n")}\n`);
fs.writeFileSync(path.join(root, "manifest.json"), JSON.stringify({ items }, null, 2) + "\n");
console.log(`[react] ${items.length} items`);
