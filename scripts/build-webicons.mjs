// File: scripts/build-webicons.mjs
// Writes the small built-in webicon set (the icons OmniaUI's own components draw by default, plus a few flags) from
// the local @iconify-json packages into the React and Vue packages and the Laravel package. No network.
// Map: list -> read sets (node_modules/@iconify-json/<set>/icons.json) -> resolve aliases -> write
//      packages/react/src/webicons-builtin.ts, packages/vue/src/webicons-builtin.ts,
//      php-packages/omniaui-laravel/resources/webicons/builtin.json, packages/ui/bin/lib/webicons-builtin.json (CLI)
// Run: node scripts/build-webicons.mjs (only when the list below changes; the output is committed).

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();

/** Icons OmniaUI's components use by default (check marks, chevrons, close, arrows, the theme switch …) and the
 *  flags of the language menu demos. Keep it small: everything else an app registers itself. */
export const BUILTIN = [
  "mdi:check", "mdi:check-all", "mdi:close", "mdi:menu", "mdi:magnify", "mdi:calendar", "mdi:dots-vertical", "mdi:content-copy",
  "mdi:chevron-down", "mdi:chevron-up", "mdi:chevron-left", "mdi:chevron-right",
  "mdi:arrow-up", "mdi:arrow-down", "mdi:arrow-left", "mdi:arrow-right", "mdi:trash-can-outline",
  "mdi:walk", "mdi:flag-checkered", "mdi:map-marker-outline", "mdi:target", "mdi:text",
  "mdi:web", "mdi:monitor", "mdi:white-balance-sunny", "mdi:weather-night", "mdi:lock-outline", "mdi:lightbulb-on-outline",
  "mdi:eye", "mdi:eye-off", "mdi:download", "mdi:printer", "mdi:alert-outline", "mdi:heart", "mdi:star",
  "material-symbols:arrow-outward-rounded",
  // 0.18.0: the icons of the status badges (Badge status="…") and the breadcrumb ellipsis.
  "mdi:check-circle-outline", "mdi:clock-outline", "mdi:alert-circle-outline", "mdi:pencil-outline", "mdi:send-outline",
  "mdi:cancel", "mdi:check-decagram-outline", "mdi:close-circle-outline", "mdi:circle-medium", "mdi:circle-off-outline",
  "mdi:archive-outline", "mdi:alert-octagon-outline", "mdi:cash-refund", "mdi:calendar-clock-outline", "mdi:progress-clock",
  "mdi:timer-sand", "mdi:sleep", "mdi:dots-horizontal",
  "flag:nl-4x3", "flag:be-4x3", "flag:fr-4x3", "flag:de-4x3", "flag:gb-4x3", "flag:it-4x3", "flag:us-4x3",
];

const sets = new Map();
const readSet = (prefix) => {
  if (!sets.has(prefix)) sets.set(prefix, JSON.parse(fs.readFileSync(path.join(root, "node_modules/@iconify-json", prefix, "icons.json"), "utf8")));
  return sets.get(prefix);
};

/** One icon of a set with its aliases resolved: { body, width, height } (+ left/top/rotate/hFlip/vFlip when set). */
export function resolveIcon(set, name) {
  let data = {};
  let n = name;
  for (let depth = 0; depth < 6; depth++) {
    const icon = set.icons[n];
    if (icon) {
      const out = { ...icon, ...data, body: icon.body };
      if (data.rotate || icon.rotate) out.rotate = ((icon.rotate ?? 0) + (data.rotate ?? 0)) % 4;
      if (data.hFlip || icon.hFlip) out.hFlip = !!icon.hFlip !== !!data.hFlip;
      if (data.vFlip || icon.vFlip) out.vFlip = !!icon.vFlip !== !!data.vFlip;
      for (const k of ["left", "top", "width", "height"]) if (out[k] == null && set[k] != null) out[k] = set[k];
      out.width ??= 16;
      out.height ??= 16;
      for (const k of ["rotate", "hFlip", "vFlip", "left", "top"]) if (!out[k]) delete out[k];
      return out;
    }
    const alias = set.aliases?.[n];
    if (!alias) return null;
    const { parent, ...rest } = alias;
    data = { ...rest, ...data, rotate: (rest.rotate ?? 0) + (data.rotate ?? 0), hFlip: !!rest.hFlip !== !!data.hFlip, vFlip: !!rest.vFlip !== !!data.vFlip };
    n = parent;
  }
  return null;
}

const out = {};
for (const full of BUILTIN) {
  const i = full.indexOf(":");
  const icon = resolveIcon(readSet(full.slice(0, i)), full.slice(i + 1));
  if (!icon) throw new Error(`[webicons] ${full} not found`);
  out[full] = icon;
}

const json = JSON.stringify(out);
const ts = `// File: <pkg>/src/webicons-builtin.ts (generated by scripts/build-webicons.mjs - do not edit by hand)
// The built-in webicons: what OmniaUI's own components draw by default, plus a few flags. Paths from the Iconify sets
// MDI (Apache 2.0), Material Symbols (Apache 2.0) and Flags (MIT), bundled, no network.
import type { WebiconData } from "./webicons";

export const BUILTIN_WEBICONS: Record<string, WebiconData> = ${json};
`;
for (const pkg of ["react", "vue"]) {
  fs.writeFileSync(path.join(root, "packages", pkg, "src/webicons-builtin.ts"), ts.replace("<pkg>", `packages/${pkg}`));
}
const phpDir = path.join(root, "php-packages/omniaui-laravel/resources/webicons");
fs.mkdirSync(phpDir, { recursive: true });
fs.writeFileSync(path.join(phpDir, "builtin.json"), JSON.stringify(out, null, 1) + "\n");
// The CLI (omniaui webicons) takes a built-in icon from here when its set is not installed in the app.
fs.writeFileSync(path.join(root, "packages/ui/bin/lib/webicons-builtin.json"), JSON.stringify(out) + "\n");
console.log(`[webicons] ${BUILTIN.length} built-in icons, ${json.length} bytes`);
